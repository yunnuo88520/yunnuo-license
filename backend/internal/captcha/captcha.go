const (
	codeLen    = 4
	scale      = 4
	glyphW     = 5
	glyphH     = 7
	marginX    = 16
	marginY    = 9
	gapX       = 10
	canvasW    = marginX*2 + codeLen*(glyphW*scale+gapX) - gapX
	canvasH    = marginY*2 + glyphH*scale
	challengeT = 5 * 60 // 秒，有效期由服务层管理
)

