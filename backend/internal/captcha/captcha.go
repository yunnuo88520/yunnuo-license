var glyphColors = []color.RGBA{
	{0x33, 0x41, 0x55, 0xff}, {0x4f, 0x46, 0xe5, 0xff},
	{0x0f, 0x76, 0x64, 0xff}, {0xb4, 0x53, 0x09, 0xff},
	{0x9d, 0x17, 0x40, 0xff}, {0x37, 0x30, 0xa3, 0xff},
}

var noiseColor = color.RGBA{0xb6, 0xc0, 0xcd, 0xff}
var bgColor = color.RGBA{0xf6, 0xf7, 0xfa, 0xff}

// NewCode 生成一串随机验证码字符。
func NewCode() (string, error) {
	out := make([]byte, codeLen)
	for i := range out {
		n, err := rand.Int(rand.Reader, big.NewInt(int64(len(Chars))))
		if err != nil {
			return "", err
		}
		out[i] = Chars[n.Int64()]
	}
	return string(out), nil
}

// Render 把验证码绘制为 PNG（带抖动、干扰线与噪点）。
func Render(code string) ([]byte, error) {
	if len(code) != codeLen {
		return nil, errors.New("captcha: code length must be 4")
	}
	img := image.NewRGBA(image.Rect(0, 0, canvasW, canvasH))
	for y := 0; y < canvasH; y++ {
		for x := 0; x < canvasW; x++ {
			img.SetRGBA(x, y, bgColor)
		}
	}
	// 噪点。
	for i := 0; i < 90; i++ {
		img.SetRGBA(mrand.Intn(canvasW), mrand.Intn(canvasH), noiseColor)
	}
	// 字形（逐像素缩放 + 抖动 + 随机缺蚀）。
	for i := 0; i < codeLen; i++ {
		glyph, ok := font[code[i]]
		if !ok {
			return nil, errors.New("captcha: unsupported character")
		}
		tone := glyphColors[mrand.Intn(len(glyphColors))]
		originX := marginX + i*(glyphW*scale+gapX)
		for row := 0; row < glyphH; row++ {
			for col := 0; col < glyphW; col++ {
				if glyph[row]&(0x10>>col) == 0 {
					continue
				}
				for dy := 0; dy < scale; dy++ {
					for dx := 0; dx < scale; dx++ {
						if mrand.Intn(100) < 7 {
							continue
						}
						x := originX + col*scale + dx + mrand.Intn(3) - 1
						y := marginY + row*scale + dy + mrand.Intn(3) - 1
						if x < 0 || y < 0 || x >= canvasW || y >= canvasH {
							continue
						}
						img.SetRGBA(x, y, tone)
					}
				}
			}
		}
	}
	// 干扰折线。
	for i := 0; i < 3; i++ {
		x := mrand.Intn(canvasW / 3)
		y := mrand.Intn(canvasH)
		for x < canvasW {
			img.SetRGBA(x, clampY(y), noiseColor)
			if x+1 < canvasW {
				img.SetRGBA(x+1, clampY(y), noiseColor)
			}
			x += 3 + mrand.Intn(4)
			y += mrand.Intn(7) - 3
		}
	}
	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func clampY(y int) int {
	if y < 1 {
		return 1
	}
	if y >= canvasH-1 {
		return canvasH - 2
	}
	return y
}
