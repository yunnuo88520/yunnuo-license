package store

import (
	"context"
	"database/sql"
	"time"
)

type ApplicationCredential struct {
	SecretHash string
	Version    int
	UpdatedAt  time.Time
}

func (s *Store) ApplicationCredential(ctx context.Context, id string) (ApplicationCredential, error) {
	var value ApplicationCredential
	var updated string
	err := s.db.QueryRowContext(ctx, `SELECT secret_hash,version,updated_at FROM application_credentials WHERE product_id=?`, id).Scan(&value.SecretHash, &value.Version, &updated)
	value.UpdatedAt = parseTS(updated)
	return value, err
}

// SetApplicationSecret serializes resets on the product row. A stale version
// cannot silently replace a secret just generated by another administrator.
func (tx *Tx) SetApplicationSecret(ctx context.Context, id, hash string, expected int, now time.Time) (int, bool, error) {
	if _, err := tx.tx.ExecContext(ctx, `UPDATE products SET updated_at=updated_at WHERE id=?`, id); err != nil {
		return 0, false, err
	}
	var version int
	err := tx.tx.QueryRowContext(ctx, `SELECT version FROM application_credentials WHERE product_id=?`, id).Scan(&version)
	if err != nil && err != sql.ErrNoRows {
		return 0, false, err
	}
	if version != expected {
		return version, false, nil
	}
	if err == sql.ErrNoRows {
		_, err = tx.tx.ExecContext(ctx, `INSERT INTO application_credentials(product_id,secret_hash,version,updated_at) VALUES(?,?,1,?)`, id, hash, ts(now))
	} else {
		_, err = tx.tx.ExecContext(ctx, `UPDATE application_credentials SET secret_hash=?,version=version+1,updated_at=? WHERE product_id=?`, hash, ts(now), id)
	}
	return version + 1, err == nil, err
}
